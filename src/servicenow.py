"""ServiceNow integration: AI-suggested answers on new incidents, posted as work notes.

Flow (setup and results: README, "ServiceNow integration"):
  1. A Business Rule on the incident table fires after insert (async, so the agent never waits)
     and POSTs only {"sys_id", "number"} to /servicenow/events, signed with HMAC-SHA256 over
     "<timestamp>.<body>" (x-timestamp and x-signature headers).
  2. The webhook Lambda verifies the signature and its age (5 minutes, so requests can't be replayed), records the sys_id in DynamoDB (so one incident never
     gets two AI notes), and queues it in SQS. It answers 202 right away.
  3. The worker Lambda reads the queue, fetches the incident from ServiceNow itself (the webhook
     body is never trusted for content), asks the knowledge base assistant, and writes the result
     back as a work note. Work notes are internal: only IT staff see them, never the caller.
  4. Failures retry through SQS; after 3 tries the message goes to a dead-letter queue with an alarm.

In "suggest" mode (this module's process_incident) the AI only suggests: it never changes state,
priority, or assignment, and never contacts the caller. In "agent" mode (agent.py, the default) the
AI works the ticket: it sends a verified KB fix to the caller and waits for them to confirm, or
escalates to the right team.
"""
import base64
import http.client
import json
import logging
import re
import time
import urllib.error
import urllib.parse
import urllib.request

logger = logging.getLogger(__name__)

SYS_ID = re.compile(r"[0-9a-f]{32}")
NUMBER = re.compile(r"[A-Z]{2,8}\d{4,12}")
FIELDS = ("sys_id,number,short_description,description,active,work_notes,comments,priority,state,"
          "assigned_to,caller_id")
MAX_DESCRIPTION = 700  # keep the question within the assistant's 1000-character limit

NOTE_HEADER = "[AI Suggested Response - IT KB Assistant]"
NOTE_FOOTER = ("Generated by AI from the IT knowledge base. Review before using; "
               "this note is visible to IT staff only.")


class ServiceNowError(Exception):
    def __init__(self, message: str, status: int | None = None):
        super().__init__(message)
        self.status = status


class ServiceNowClient:
    """Minimal Table API client (standard library only). Uses a least-privilege service account."""

    RETRY_STATUS = (429, 500, 502, 503, 504)

    def __init__(self, instance_url: str, user: str, password: str, opener=urllib.request.urlopen,
                 timeout: int = 10, waits=(1, 3), sleep=time.sleep):
        url = (instance_url or "").strip().rstrip("/")
        if url and "://" not in url:
            url = "https://" + url
        if not url.startswith("https://"):
            raise ServiceNowError("SERVICENOW_INSTANCE_URL must be an https:// URL")
        if not user or not password:
            raise ServiceNowError("ServiceNow credentials are not configured")
        self.base = url
        self.auth = "Basic " + base64.b64encode(f"{user}:{password}".encode()).decode()
        self.opener = opener
        self.timeout = timeout
        self.waits = tuple(waits)
        self.sleep = sleep

    def _request(self, method: str, path: str, body: dict | None = None, query: dict | None = None) -> dict:
        url = self.base + path + ("?" + urllib.parse.urlencode(query) if query else "")
        data = json.dumps(body).encode("utf-8") if body is not None else None
        for wait in self.waits + (None,):
            request = urllib.request.Request(url, data=data, method=method, headers={
                "Authorization": self.auth, "Accept": "application/json", "Content-Type": "application/json"})
            try:
                with self.opener(request, timeout=self.timeout) as response:
                    return json.loads(response.read().decode("utf-8") or "{}")
            except urllib.error.HTTPError as error:
                # 429 means "not processed, slow down", so it's always safe to retry. Other errors
                # and timeouts are retried only for reads: a write that timed out may have been saved
                # (ServiceNow can be slow to answer), and a work-note PATCH or POST isn't idempotent.
                retryable = error.code == 429 or (method == "GET" and error.code in self.RETRY_STATUS)
                if retryable and wait is not None:
                    logger.warning("ServiceNow returned %s, retrying in %ss", error.code, wait)
                    self.sleep(wait)
                    continue
                raise ServiceNowError(f"ServiceNow {method} {path.split('?')[0]} failed: HTTP {error.code}",
                                      error.code) from error
            except (OSError, ValueError, http.client.HTTPException) as error:  # timeouts, bad JSON
                if wait is not None and method == "GET":
                    self.sleep(wait)
                    continue
                raise ServiceNowError(f"ServiceNow request failed: {type(error).__name__}") from error
        raise ServiceNowError("unreachable")  # pragma: no cover

    # Generic Table API helpers (used by the setup and eval scripts with an admin account)
    def query(self, table: str, query: str = "", fields: str = "", limit: int = 100, order_by: str = "") -> list:
        params = {"sysparm_query": query + (f"^ORDERBY{order_by}" if order_by else ""),
                  "sysparm_limit": str(limit), "sysparm_exclude_reference_link": "true"}
        if fields:
            params["sysparm_fields"] = fields
        return self._request("GET", f"/api/now/table/{table}", query=params).get("result", [])

    def create(self, table: str, record: dict) -> dict:
        return self._request("POST", f"/api/now/table/{table}", body=record).get("result", {})

    def update(self, table: str, sys_id: str, record: dict, display_values: bool = False) -> dict:
        query = {"sysparm_input_display_value": "true"} if display_values else None
        return self._request("PATCH", f"/api/now/table/{table}/{sys_id}", body=record, query=query).get("result", {})

    def delete(self, table: str, sys_id: str) -> None:
        self._request("DELETE", f"/api/now/table/{table}/{sys_id}")

    def get_incident(self, sys_id: str) -> dict | None:
        if not SYS_ID.fullmatch(sys_id or ""):
            raise ServiceNowError("invalid sys_id")
        try:
            data = self._request("GET", f"/api/now/table/incident/{sys_id}",
                                 query={"sysparm_fields": FIELDS, "sysparm_display_value": "true",
                                        "sysparm_exclude_reference_link": "true"})
        except ServiceNowError as error:
            if error.status == 404:
                return None
            raise
        return data.get("result") or None

    def add_work_note(self, sys_id: str, note: str) -> None:
        if not SYS_ID.fullmatch(sys_id or ""):
            raise ServiceNowError("invalid sys_id")
        self._request("PATCH", f"/api/now/table/incident/{sys_id}", body={"work_notes": note},
                      query={"sysparm_fields": "sys_id"})


def incident_question(incident: dict) -> str:
    """Turn the incident's short description and description into one question for the assistant."""
    short = " ".join(str(incident.get("short_description") or "").split())
    detail = " ".join(str(incident.get("description") or "").split())
    if detail and detail.lower() != short.lower():
        detail = detail[:MAX_DESCRIPTION]
        return f"{short}. Details: {detail}" if short else detail
    return short


def _plain(text: str) -> str:
    """Work notes are plain text in ServiceNow, so drop Markdown bold/italic markers."""
    return re.sub(r"\*\*(.+?)\*\*", r"\1", text).replace("__", "")


def format_work_note(result: dict) -> str:
    """Plain-text work note for the agent. Says clearly what the AI did and didn't find."""
    status = result.get("status")
    lines = [NOTE_HEADER]
    if status == "answered":
        lines += ["Suggested resolution (from the knowledge base):", "", _plain(result.get("answer", "").strip()),
                  "", "Sources:"]
        by_doc = {}
        for s in result.get("sources", []):  # several cited chunks can come from the same article
            by_doc.setdefault((s["title"], s["source"]), []).append(s["n"])
        lines += [f"{''.join(f'[{n}]' for n in nums)} {title} ({source})" for (title, source), nums in by_doc.items()]
        if (result.get("guardrail", {}).get("output") or {}).get("scores"):
            lines += ["", "Checked by Amazon Bedrock Guardrails: grounded in the cited articles and relevant."]
    elif status == "no_answer":
        lines += ["No knowledge base article covers this incident, so no answer is suggested.",
                  "Next step: troubleshoot as usual. If this issue repeats, consider writing a KB article."]
    elif status == "blocked":
        lines += ["No suggestion: the incident text matched a security policy (for example, a request to",
                  "bypass security tools or share credentials). Review it manually."]
    else:
        lines += ["The AI assistant was unavailable for this incident. No suggestion was made."]
    lines += ["", NOTE_FOOTER]
    return "\n".join(lines)


class RetryLater(Exception):
    """The assistant had a temporary failure; let SQS deliver the message again."""


def process_incident(client: ServiceNowClient, assistant, sys_id: str, time_left=None,
                     final_attempt: bool = True) -> dict:
    """Fetch the incident, ask the assistant, write the work note. Returns a small summary for logs.
    If the assistant errors and this isn't the last attempt, raise RetryLater instead of writing an
    "unavailable" note, so a temporary outage doesn't leave a useless note on the incident."""
    incident = client.get_incident(sys_id)
    if incident is None:
        return {"sys_id": sys_id, "outcome": "not_found"}
    if str(incident.get("active", "true")).lower() == "false":
        return {"sys_id": sys_id, "number": incident.get("number"), "outcome": "inactive"}
    if NOTE_HEADER in str(incident.get("work_notes") or ""):
        # Already noted (e.g. a write that timed out but was saved, then retried): never add a second note.
        return {"sys_id": sys_id, "number": incident.get("number"), "outcome": "already_noted"}
    question = incident_question(incident)
    if not question:
        return {"sys_id": sys_id, "number": incident.get("number"), "outcome": "empty"}
    result = assistant.ask(question, time_left=time_left)
    if result.get("status") == "error" and not final_attempt:
        raise RetryLater(f"assistant error on {incident.get('number')}")
    client.add_work_note(sys_id, format_work_note(result))
    return {"sys_id": sys_id, "number": incident.get("number"), "outcome": "noted",
            "status": result.get("status"), "provider": result.get("provider"),
            "sources": [s["source"] for s in result.get("sources", [])],
            "usage": result.get("usage"), "latency_ms": result.get("latency_ms")}
